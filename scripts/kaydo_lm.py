#!/usr/bin/env python3
"""Local-only helpers for the Kaydo developer toolkit.

Uses only Python's standard library. This file never applies migrations or
executes output generated by a model.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Any
from urllib.error import URLError, HTTPError
from urllib.request import Request, urlopen

LM_BASE_URL = "http://127.0.0.1:1234/v1"
MAX_CONTEXT_CHARS = 12_000


def redact(text: str) -> str:
    """Redact common credential formats before text leaves the repository."""
    patterns = (
        # URLs with user/password material.
        (r"(://[^\s:@/]+:)[^\s@/]+@", r"\1[REDACTED]@"),
        # Header and environment styles.
        (r"(?im)\b(authorization\s*:\s*bearer\s+)[^\s]+", r"\1[REDACTED]"),
        (r"(?im)\b([A-Z][A-Z0-9_]*(?:TOKEN|SECRET|PASSWORD|API_KEY|PRIVATE_KEY)\s*=\s*)[^\s]+", r"\1[REDACTED]"),
        # Common credential tokens.
        (r"\b(?:gh[opsu]_[A-Za-z0-9_]+|sbp?_[A-Za-z0-9_-]+|eyJ[A-Za-z0-9_-]{20,})\b", "[REDACTED_TOKEN]"),
        # Email addresses are personal data, not required for summaries.
        (r"\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b", "[REDACTED_EMAIL]"),
    )
    result = text
    for pattern, replacement in patterns:
        result = re.sub(pattern, replacement, result, flags=re.IGNORECASE)
    return result


def run(command: list[str], cwd: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(command, cwd=cwd, text=True, capture_output=True, check=False)


def append_log(log: Path, text: str) -> None:
    log.parent.mkdir(parents=True, exist_ok=True)
    with log.open("a", encoding="utf-8") as handle:
        handle.write(text)
        if not text.endswith("\n"):
            handle.write("\n")


def extract_migration_payload(output: str) -> dict[str, Any] | None:
    """The CLI can prefix JSON with warnings; locate its migration payload."""
    marker = '{"migrations"'
    start = output.find(marker)
    if start < 0:
        return None
    decoder = json.JSONDecoder()
    try:
        payload, _ = decoder.raw_decode(output[start:])
    except json.JSONDecodeError:
        return None
    return payload if isinstance(payload, dict) else None


def parse_migration_table(output: str) -> tuple[str | None, list[dict[str, str]]] | None:
    """Parse the CLI's stable human table when it does not honor --output json."""
    project_match = re.search(r"Target: project .*?\(([^)]+)\)", output)
    rows: list[dict[str, str]] = []
    for line in output.splitlines():
        match = re.match(
            r"\s*`?\s*([0-9]*)\s*`?\s*\|\s*`?\s*([0-9]*)\s*`?\s*\|",
            line,
        )
        if match:
            local, remote = match.groups()
            if local or remote:
                rows.append({"local": local, "remote": remote})
    if not project_match or not rows:
        return None
    return project_match.group(1), rows


def db_check(args: argparse.Namespace) -> int:
    repo = Path(args.repo).resolve()
    log = Path(args.log).resolve()
    local_migrations = sorted(path.stem.split("_")[0] for path in (repo / "supabase/migrations").glob("*.sql"))
    append_log(log, f"Kaydo db-check started: {dt.datetime.now().isoformat()}\nExpected project: {args.project_ref}\n")
    append_log(log, "Local migration versions:\n" + "\n".join(local_migrations) + "\n")

    # --remote is Supabase's supported read-only listing mode. No db push,
    # repair, reset, or migration-apply command is ever invoked here.
    result = run(["supabase", "migration", "list", "--remote", "--output", "json"], repo)
    append_log(log, "\nRemote command: supabase migration list --remote --output json\n")
    append_log(log, redact(result.stdout + result.stderr))
    if result.returncode != 0:
        print("LIMITED: unable to read remote migration history; no database changes were made.", file=sys.stderr)
        return 1
    payload = extract_migration_payload(result.stdout)
    if payload is not None:
        target = payload.get("target") or {}
        project_ref = target.get("project_ref")
        rows = payload.get("migrations") or []
    else:
        # Supabase CLI v3 currently prints a formatted migration table even
        # when --output json is supplied. Accept only a table that includes a
        # project ref and concrete migration rows; otherwise report limitation.
        parsed = parse_migration_table(result.stdout + result.stderr)
        if parsed is None:
            print("LIMITED: Supabase CLI returned no parseable migration history; no database changes were made.", file=sys.stderr)
            return 1
        project_ref, rows = parsed
    if project_ref != args.project_ref:
        print(f"FAIL: expected project {args.project_ref}, got {project_ref or 'unknown'}.", file=sys.stderr)
        return 1

    local_only = sorted(str(row.get("local")) for row in rows if row.get("local") and not row.get("remote"))
    remote_only = sorted(str(row.get("remote")) for row in rows if row.get("remote") and not row.get("local"))
    both = sorted(str(row.get("local")) for row in rows if row.get("local") and row.get("remote"))
    summary = (
        f"\nProject verified: {project_ref}\n"
        f"Matching migrations: {len(both)}\n"
        f"Local-only (pending or divergent): {', '.join(local_only) or 'none'}\n"
        f"Remote-only (history divergence): {', '.join(remote_only) or 'none'}\n"
    )
    append_log(log, summary)
    print(summary, end="")
    if local_only or remote_only:
        print("FAIL: migration history is divergent. db-check will not repair, apply, or mark migrations.", file=sys.stderr)
        return 1
    return 0


def latest_log(repo: Path) -> Path | None:
    logs = sorted((repo / ".kaydo/logs").glob("*.log"), key=lambda path: path.stat().st_mtime, reverse=True)
    return logs[0] if logs else None


def lm_request(path: str, payload: dict[str, Any]) -> dict[str, Any]:
    request = Request(
        f"{LM_BASE_URL}{path}",
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    with urlopen(request, timeout=30) as response:  # noqa: S310 - fixed localhost URL
        return json.load(response)


def lm_models() -> list[str]:
    request = Request(f"{LM_BASE_URL}/models", method="GET")
    with urlopen(request, timeout=5) as response:  # noqa: S310 - fixed localhost URL
        payload = json.load(response)
    return [str(item["id"]) for item in payload.get("data", []) if item.get("id")]


def ask_lm(prompt: str, model_override: str | None) -> tuple[str, str]:
    try:
        models = lm_models()
    except (URLError, HTTPError, TimeoutError, OSError) as exc:
        raise RuntimeError(f"LM Studio is unavailable at {LM_BASE_URL}: {exc}") from exc
    model = model_override or (models[0] if models else None)
    if not model:
        raise RuntimeError("LM Studio returned no loaded models. Load a model or pass --model.")
    try:
        response = lm_request(
            "/chat/completions",
            {
                "model": model,
                "temperature": 0.2,
                "messages": [
                    {
                        "role": "system",
                        "content": "You summarize developer evidence. Never claim unverified facts, never propose executing commands, and keep your response concise.",
                    },
                    {"role": "user", "content": prompt},
                ],
            },
        )
    except (URLError, HTTPError, TimeoutError, OSError) as exc:
        raise RuntimeError(f"LM Studio completion failed: {exc}") from exc
    choices = response.get("choices") or []
    if not choices:
        raise RuntimeError("LM Studio returned no completion choices.")
    content = choices[0].get("message", {}).get("content")
    if not isinstance(content, str) or not content.strip():
        raise RuntimeError("LM Studio returned an empty completion.")
    return model, content.strip()


def explain(args: argparse.Namespace) -> int:
    repo = Path(args.repo).resolve()
    source = Path(args.file).expanduser().resolve() if args.file else latest_log(repo)
    if source is None or not source.is_file():
        print("FAIL: no log found. Run `kaydo check`/`kaydo build` or pass --file PATH.", file=sys.stderr)
        return 2
    text = redact(source.read_text(encoding="utf-8", errors="replace"))[:MAX_CONTEXT_CHARS]
    prompt = (
        "This is sanitized local developer-tool output. Provide: (1) a short explanation, "
        "(2) the most relevant failure lines quoted exactly from the input, and "
        "(3) suggested investigation steps. Mark all conclusions as tentative. "
        f"Log path: {source.name}\n\n{text}"
    )
    try:
        model, response = ask_lm(prompt, args.model)
    except RuntimeError as exc:
        print(f"LIMITED: {exc}", file=sys.stderr)
        return 1
    print(f"LM Studio model: {model}\n\nProposed explanation (not verified):\n{response}")
    return 0


def pr_draft(args: argparse.Namespace) -> int:
    repo = Path(args.repo).resolve()
    branch = run(["git", "branch", "--show-current"], repo).stdout.strip()
    if not branch or branch in {"main", "master"}:
        print("FAIL: pr-draft requires a feature branch with commits to describe.", file=sys.stderr)
        return 2
    base = run(["git", "merge-base", "HEAD", "origin/main"], repo)
    if base.returncode != 0:
        base = run(["git", "merge-base", "HEAD", "main"], repo)
    if base.returncode != 0:
        print("FAIL: cannot find a main branch merge-base for the draft.", file=sys.stderr)
        return 1
    base_sha = base.stdout.strip()
    commits = run(["git", "log", "--format=%h %s", f"{base_sha}..HEAD"], repo)
    diff = run(["git", "diff", "--no-ext-diff", "--unified=2", f"{base_sha}..HEAD"], repo)
    context = redact(("Commits:\n" + commits.stdout + "\nDiff:\n" + diff.stdout)[:MAX_CONTEXT_CHARS])
    prompt = (
        "Draft PR text from sanitized Git evidence. Return exactly a proposed title and a concise Markdown "
        "description with Summary and Testing sections. Do not claim tests passed unless the input says so. "
        "This is proposed text only; it will not be submitted automatically.\n\n" + context
    )
    try:
        model, response = ask_lm(prompt, args.model)
    except RuntimeError as exc:
        print(f"LIMITED: {exc}", file=sys.stderr)
        return 1
    print(f"LM Studio model: {model}\n\nProposed PR text (not created or pushed):\n{response}")
    return 0


def parser() -> argparse.ArgumentParser:
    root = argparse.ArgumentParser(add_help=False)
    sub = root.add_subparsers(dest="command", required=True)
    db = sub.add_parser("db-check")
    db.add_argument("--repo", required=True)
    db.add_argument("--project-ref", required=True)
    db.add_argument("--log", required=True)
    explain_parser = sub.add_parser("explain")
    explain_parser.add_argument("--repo", required=True)
    explain_parser.add_argument("--file")
    explain_parser.add_argument("--model")
    draft = sub.add_parser("pr-draft")
    draft.add_argument("--repo", required=True)
    draft.add_argument("--model")
    return root


def main() -> int:
    args = parser().parse_args()
    if args.command == "db-check":
        return db_check(args)
    if args.command == "explain":
        return explain(args)
    if args.command == "pr-draft":
        return pr_draft(args)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
